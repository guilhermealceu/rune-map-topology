export interface PfSenseUser {
  name: string;
  descr: string;
  priv: string[];
  password?: string;
}

export interface PfSenseInterface {
  id: string;
  descr: string;
  if: string;
  enable: boolean;
  ipaddr: 'dhcp' | 'static' | string;
  subnet?: string;
  gateway?: string;
  ipaddrv6?: 'dhcp6' | 'slaac' | string;
  subnetv6?: string;
}

export interface PfSenseVlan {
  if: string;                // Parent interface physical, e.g., 'igc0', 'igc1'
  tag: string;               // VLAN tag, e.g., '10'
  descr: string;             // Description, e.g., 'LAN Finance'
  vlanif?: string;           // Custom/Autogenerated interface name, e.g., 'vlan0.10'
}

export interface PfSenseConfig {
  version?: string;
  system: {
    hostname: string;
    domain: string;
    dnsserver: string[];
    timezone: string;
    timeservers: string;
    optimization: 'normal' | 'high-latency' | 'aggressive' | 'conservative';
    hardware_profile?: 'physical' | 'proxmox' | 'vmware' | 'hyperv';
    dnsallowoverride: boolean;
    dnsresolutionbehavior?: 'local_fallback' | 'remote_only' | 'local_only';
    language?: string;
    prefer_ipv4?: boolean;
    ipv6allow?: boolean;
    dnslocalhost?: 'local' | 'remote' | 'both';
    ssh: {
      enable: boolean;
      port: string;
      sshguard_whitelist: string;
    };
  };
  users: PfSenseUser[];
  interfaces: PfSenseInterface[];
  dhcpd: {
    [key: string]: {
      enable: boolean;
      range: {
        from: string;
        to: string;
      };
      dnsserver?: string[];
      gateway?: string;
      pools?: Array<{ from: string; to: string }>;
      staticmap?: Array<{
        mac: string;
        ipaddr: string;
        hostname: string;
        descr: string;
      }>;
    };
  };
  filter?: {
    rule: Array<{
      type: string;
      interface: string;
      ipprotocol: string;
      protocol: string;
      source: { any?: boolean; network?: string; address?: string; };
      destination: { any?: boolean; network?: string; address?: string; port?: string; };
      descr: string;
    }>;
  };
  nat: {
    rule: Array<{
      interface: string;
      protocol: string;
      target: string;
      localport: string;
      destination: {
        port: string;
      };
      descr: string;
    }>;
    outbound?: {
      mode: 'automatic' | 'hybrid' | 'manual' | 'disabled';
    };
  };
  gateways: {
    gateway_item: Array<{
      name: string;
      interface: string;
      gateway: string;
      monitor?: string;
      descr: string;
      weight?: number;
    }>;
    gateway_group: Array<{
      name: string;
      items: Array<{
        gateway: string;
        tier: number;
      }>;
      trigger: string;
      descr: string;
    }>;
    defaultgw4?: string;
  };
  aliases: {
    alias: Array<{
      name: string;
      type: 'host' | 'network';
      address: string;
      descr: string;
    }>;
  };
  unbound: {
    hosts: Array<{
      host: string;
      domain: string;
      ip: string;
      descr: string;
    }>;
  };
  staticroutes: {
    route: Array<{
      network: string;
      gateway: string;
      descr: string;
    }>;
  };
  ipsec: {
    phase1: Array<{
      ikeid: string;
      remote_gateway: string;
      interface: string;
      descr: string;
      authentication_method: string;
      pre_shared_key: string;
      encryption_algorithm: {
        name: string;
        keylen?: string;
      };
      hash_algorithm: string;
      dhgroup: string;
    }>;
    phase2: Array<{
      ikeid: string;
      mode: string;
      localid: { type: string; address?: string; netbits?: string };
      remoteid: { type: string; address?: string; netbits?: string };
      protocol: string;
      encryption_algorithm_option: Array<{ name: string; keylen?: string }>;
      hash_algorithm_option: string[];
      pfsgroup: string;
      descr: string;
    }>;
  };
  dyndns?: {
    item: Array<{
      id?: string;
      type: string;
      interface: string;
      host: string;
      username: string;
      password?: string;
      domainname?: string;
      descr: string;
      enable?: boolean;
    }>;
  };
  openvpn?: {
    server?: Array<{
      vpnid: string;
      mode: string;
      protocol: string;
      dev_mode: string;
      interface: string;
      local_port: string;
      description: string;
      custom_options?: string;
    }>;
  };
  zabbix?: {
    agent?: {
      enabled: boolean;
      server: string;
      serveractive: string;
      hostname: string;
      listenport: string;
      tlsconnect?: string;
      tlsaccept?: string;
    };
    proxy?: {
      enabled: boolean;
      server: string;
      serverport: string;
      hostname: string;
      proxymode: string;
    };
  };
  vlans?: PfSenseVlan[];
}

export type WizardStep = 'start' | 'general' | 'users' | 'interfaces' | 'gateways' | 'services' | 'nat' | 'vpn' | 'review';
